function career(
  id: string,
  title: string,
  hi: string,
  mr: string,
  category: string,
  interests: string[],
  education: number,
  route: string,
  duration: string,
  courseIds: string[],
  description: string,
  trial: Career["trial"],
  color = "mint",
): Career {
  return {
    id,
    title,
    hi,
    mr,
    category,
    interests,
    education,
    route,
    duration,
    courseIds,
    description,
    skills: COURSES.filter((c) => courseIds.includes(c.id))
      .flatMap((c) => c.skills)
      .slice(0, 3),
    source: "https://www.ncs.gov.in/",
    sourceLabel: "National Career Service",
    color,
    trial,
  };
}
